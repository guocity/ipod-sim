import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { cp } from 'node:fs/promises';

const root = fileURLToPath(new URL('../', import.meta.url));
await build({
  absWorkingDir: root,
  entryPoints: ['packages/web-music-ipod/src/index.js'],
  outfile: 'dist/includes/ipod/web-music-ipod.esm.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: false,
  sourcemap: true,
  sourcesContent: true,
  banner: { js: '// Generated by pnpm build. Edit packages/web-music-ipod/src instead.' },
  loader: { '.woff2': 'dataurl', '.png': 'dataurl', '.wav': 'dataurl', '.css': 'text' },
  logLevel: 'info'
});
await cp(new URL('../packages/web-music-ipod/src/data/', import.meta.url),
  new URL('../dist/includes/ipod/data/', import.meta.url), { recursive: true });
